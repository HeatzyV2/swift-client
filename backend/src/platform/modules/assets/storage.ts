// Storage abstraction: the platform only talks to this interface. Local disk is the implementation shipped
// today; an S3/R2 provider can be added behind the same interface without touching the modules.
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve, sep } from 'node:path'
import { env } from '../../../env.js'

export interface StorageProvider {
  put(key: string, data: Buffer): Promise<void>
  get(key: string): Promise<Buffer | null>
  delete(key: string): Promise<void>
  /** Public URL a client can fetch. */
  url(key: string): string
}

class LocalStorage implements StorageProvider {
  private readonly root = resolve(env.dataDir, 'assets')

  /** Keys are generated by the platform, but resolve defensively so a key can never leave the root. */
  private path(key: string): string {
    const p = resolve(this.root, key)
    if (!p.startsWith(this.root + sep)) throw new Error('invalid storage key')
    return p
  }

  async put(key: string, data: Buffer) {
    const p = this.path(key)
    mkdirSync(dirname(p), { recursive: true })
    writeFileSync(p, data)
  }

  async get(key: string) {
    const p = this.path(key)
    return existsSync(p) ? readFileSync(p) : null
  }

  async delete(key: string) {
    rmSync(this.path(key), { force: true })
  }

  url(key: string) {
    const base = env.cdnBaseUrl || `${env.publicUrl}/cdn`
    return `${base}/assets/${key}`
  }
}

export const storage: StorageProvider = new LocalStorage()
